def font(style, size, bold=False):
    style.font.name = 'Heiti SC'
    style.font.size = Pt(size)
    style.font.bold = bold
    style.font.color.rgb = RGBColor(0, 0, 0)
    style.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), 'Heiti SC')

def build(title, pages, filename):
    d = Document()
    for st in d.styles:
        for border in list(st.element.iter(qn('w:pBdr'))):
            border.getparent().remove(border)
    s = d.sections[0]
    s.page_width, s.page_height = Inches(8.27), Inches(11.69)
    s.top_margin, s.bottom_margin = Inches(.65), Inches(.65)
    s.left_margin = s.right_margin = Inches(.75)
    font(d.styles['Normal'], 10.5)
    d.styles['Normal'].paragraph_format.line_spacing = 1.16
    d.styles['Normal'].paragraph_format.space_after = Pt(7)
    font(d.styles['Title'], 23, True)
    font(d.styles['Heading 1'], 17, True)
    font(d.styles['Heading 2'], 11.5, True)
    d.styles['Heading 1'].paragraph_format.space_after = Pt(12)
    d.styles['Heading 2'].paragraph_format.space_before = Pt(8)
    d.styles['Heading 2'].paragraph_format.space_after = Pt(4)
    footer = s.footer.paragraphs[0]
    footer.alignment = 2
    r = footer.add_run('云上列车  V0.1  |  ')
    r.font.size = Pt(9)
    field = OxmlElement('w:fldSimple'); field.set(qn('w:instr'), 'PAGE')
    footer._p.append(field)
    for i, (section, entries) in enumerate(pages):
        if i:
            d.add_page_break()
        else:
            d.add_paragraph(title, 'Title')
            d.add_paragraph('V0.1  ·  2026 年 10 月 23 日')
        d.add_heading(f'{i+1}  {section}', 1)
        for heading, body in entries:
            d.add_heading(heading, 2)
            d.add_paragraph(body)
    d.core_properties.title = title
    d.core_properties.subject = '云上列车首版设计'
    d.core_properties.author = 'AIGame003'
    d.save(OUT / filename)

build('云上列车游戏设计文档', GDD, '云上列车_游戏设计文档_V0.1.docx')
